export type Domain = 'lv' | 'effusion';
export type Mode = 'human-first' | 'ai-first' | 'unaided' | 'guided';
export type ErrorType = 'none' | 'missed-finding' | 'over-call' | 'wrong-grade';

export type ClipSpec =
  | {
      kind: 'synthetic';
      /** LV ejection fraction, 0–1 */
      ef: number;
      /** Pericardial effusion size, 0 (none) to 1 (large) */
      effusion: number;
      /** Epicardial fat pad that can mimic a small effusion */
      mimic?: boolean;
      hr: number;
      view: 'A4C';
    }
  | { kind: 'video'; src: string; view?: string };

export interface AIOutput {
  answer: string;
  /** Confidence the simulated AI displays, 0–1 */
  confidence: number;
  errorType: ErrorType;
}

export interface CaseOption {
  value: string;
  label: string;
}

export interface CaseItem {
  id: string;
  pairId: string;
  domain: Domain;
  question: string;
  options: CaseOption[];
  answer: string;
  difficulty: 1 | 2 | 3;
  rationale: string;
  lookFor: string;
  clip: ClipSpec;
  ai: { correct: AIOutput; wrong: AIOutput };
  status: 'draft' | 'reviewed';
}

export type OutcomeClass =
  | 'caught-error'
  | 'automation-bias'
  | 'missed-error'
  | 'aligned'
  | 'appropriate-reliance'
  | 'under-reliance'
  | 'assisted-correct'
  | 'assisted-incorrect'
  | 'unaided-correct'
  | 'unaided-incorrect';

export type ReasonCode =
  | 'INSUFFICIENT_EVIDENCE'
  | 'AUTOMATION_BIAS_PATTERN'
  | 'LOW_INDEPENDENT_ACCURACY'
  | 'OVERCONFIDENCE'
  | 'VERIFIED_INDEPENDENCE'
  | 'DEFAULT_SCHEDULE';

export interface Trainee {
  id: string;
  name: string;
  createdAt: number;
  /** Persona key when the trainee was generated by the simulator */
  persona?: string;
}

export interface PolicyDecision {
  id: string;
  traineeId: string;
  at: number;
  domain: Domain;
  mode: Mode;
  caseId: string;
  aiWrong: boolean;
  errorRate: number;
  reasonCode: ReasonCode;
  explanation: string;
  pairSlot: boolean;
  flags: { reflection?: boolean; calibrationPrompt?: boolean };
  policyVersion: string;
}

export interface Attempt {
  id: string;
  traineeId: string;
  decisionId: string;
  caseId: string;
  pairId: string;
  domain: Domain;
  mode: Mode;
  pairSlot: boolean;
  aiShown: boolean;
  aiCorrect: boolean | null;
  aiAnswer: string | null;
  aiErrorType: ErrorType | null;
  initialAnswer: string;
  initialConfidence: number;
  finalAnswer: string;
  finalConfidence: number | null;
  switched: boolean;
  firstCorrect: boolean;
  finalCorrect: boolean;
  outcome: OutcomeClass;
  reasonCode: ReasonCode;
  reflection?: string;
  durationMs: number;
  createdAt: number;
}

export interface PairAssignment {
  pairId: string;
  aiFirstCaseId: string;
  unaidedCaseId: string;
  firstHalf: 'ai-first' | 'unaided';
}
